#!/usr/bin/env python3
"""Run the LORC VLDB-style YCSB experiment matrix and generate paper figures.

The script is intentionally conservative:
  * read-only workloads run directly on prepared source databases;
  * auto compaction is disabled for read-only source reuse;
  * write/update workloads copy the source database into the run directory;
  * direct reads are disabled by default for hot-cache experiments.
"""

from __future__ import annotations

import argparse
import csv
import math
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterable

import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter


ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT.parent / "68368b2dccae04737d71ce11"
SOURCE_POSTFIX = "source-24B-1KB-4GB"
RECORDCOUNT = 4_000_000
FIELD_LENGTH = 1024
YCSB_DB = "rocksdb_lorc"
DIRECT_READS = "false"


@dataclass(frozen=True)
class Variant:
    label: str
    db: str
    lorc: bool
    prop_file: str

    @property
    def key(self) -> str:
        return self.label.lower().replace("+", "_").replace(" ", "_")

    def source_path(self, distribution: str = "random") -> Path:
        return (
            ROOT
            / "db"
            / f"ycsb-{SOURCE_POSTFIX}"
            / f"ycsb-{self.db}-{SOURCE_POSTFIX}-{distribution}"
        )


VARIANTS = [
    Variant("RocksDB", "rocksdb", False, "rocksdb.properties"),
    Variant("RocksDB+LORC", "rocksdb", True, "rocksdb_lorc.properties"),
    Variant("BlobDB", "blobdb", False, "blobdb.properties"),
    Variant("BlobDB+LORC", "blobdb", True, "blobdb_lorc.properties"),
]


METRIC_RE = re.compile(
    r"\[(?P<op>[A-Z]+): Count=(?P<count>\d+) Max=(?P<max>[\d.]+) "
    r"Min=(?P<min>[\d.]+) Avg=(?P<avg>[\d.]+) 90=(?P<p90>[\d.]+) "
    r"99=(?P<p99>[\d.]+) 99\.9=(?P<p999>[\d.]+) 99\.99=(?P<p9999>[\d.]+)\]"
)
SIMPLE_RE = re.compile(r"Run (?P<name>[^:]+): (?P<value>[-\d.]+)")
LORC_STATS_RE = re.compile(r"\[LORC_STATS\]\s+(?P<body>.*)")


def shell_quote(parts: Iterable[str]) -> str:
    return " ".join(subprocess.list2cmdline([p]) for p in parts)


def workload_text(
    *,
    operationcount: int,
    warmup_ratio: float,
    hot_data_ratio: float,
    readproportion: float,
    updateproportion: float,
    scanproportion: float,
    requestdistribution: str,
    scan_length: int,
    phased_ranges: str | None = None,
) -> str:
    phase_line = f"phased_ranges={phased_ranges}\n" if phased_ranges else ""
    return f"""# Generated by experiments/run_lorc_vldb_experiments.py
recordcount={RECORDCOUNT}
operationcount={operationcount}
hot_data_ratio={hot_data_ratio}
warmup_ratio={warmup_ratio:.8f}
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

zeropadding=24
fieldcount=1
fieldlength={FIELD_LENGTH}

readallfields=true
writeallfields=true

readproportion={readproportion}
updateproportion={updateproportion}
scanproportion={scanproportion}
insertproportion=0

requestdistribution={requestdistribution}
{phase_line}

minscanlength={scan_length}
maxscanlength={scan_length}
scanlengthdistribution=uniform
"""


def warmup_ops_for(
    hot_ratio: float,
    scan_prop: float,
    scan_length: int,
    *,
    min_warmup_ops: int,
    coverage_factor: float,
) -> int:
    hot_records = RECORDCOUNT * hot_ratio
    if scan_prop <= 0:
        return min_warmup_ops
    coverage_ops = math.ceil(
        coverage_factor * hot_records / max(scan_prop * scan_length, 1e-9)
    )
    return max(min_warmup_ops, coverage_ops)


def make_workload(
    out_dir: Path,
    name: str,
    *,
    measured_ops: int,
    hot_ratio: float = 0.05,
    read_prop: float = 0.0,
    update_prop: float = 0.0,
    scan_prop: float = 1.0,
    distribution: str = "zipfian",
    scan_length: int = 20,
    min_warmup_ops: int = 50_000,
    coverage_factor: float = 2.0,
    phased_ranges: str | None = None,
) -> tuple[Path, int, int, float]:
    warmup = warmup_ops_for(
        hot_ratio,
        scan_prop,
        scan_length,
        min_warmup_ops=min_warmup_ops,
        coverage_factor=coverage_factor,
    )
    total_ops = warmup + measured_ops
    warmup_ratio = warmup / total_ops
    path = out_dir / f"{name}.properties"
    path.write_text(
        workload_text(
            operationcount=total_ops,
            warmup_ratio=warmup_ratio,
            hot_data_ratio=hot_ratio,
            readproportion=read_prop,
            updateproportion=update_prop,
            scanproportion=scan_prop,
            requestdistribution=distribution,
            scan_length=scan_length,
            phased_ranges=phased_ranges,
        )
    )
    return path, total_ops, warmup, warmup_ratio


def parse_log(text: str) -> dict[str, float | int | str]:
    out: dict[str, float | int | str] = {}
    metrics: dict[str, dict[str, float | int]] = {}
    for match in METRIC_RE.finditer(text):
        op = match.group("op").lower()
        metrics[op] = {
            "count": int(match.group("count")),
            "max_us": float(match.group("max")),
            "min_us": float(match.group("min")),
            "avg_us": float(match.group("avg")),
            "p90_us": float(match.group("p90")),
            "p99_us": float(match.group("p99")),
            "p999_us": float(match.group("p999")),
            "p9999_us": float(match.group("p9999")),
        }
    for op, values in metrics.items():
        for key, value in values.items():
            out[f"{op}_{key}"] = value
    for match in SIMPLE_RE.finditer(text):
        name = match.group("name").strip().lower().replace(" ", "_").replace("(", "").replace(")", "")
        value = match.group("value")
        out[name] = float(value)
    for match in LORC_STATS_RE.finditer(text):
        for token in match.group("body").split():
            if "=" not in token:
                continue
            key, value = token.split("=", 1)
            try:
                out[f"lorc_{key}"] = float(value)
            except ValueError:
                out[f"lorc_{key}"] = value
    if "measured_throughputops/sec" in out:
        out["throughputops/sec"] = out["measured_throughputops/sec"]
    return out


def run_one(
    *,
    run_dir: Path,
    workload: Path,
    variant: Variant,
    experiment: str,
    distribution: str,
    read_only: bool,
    extra_props: dict[str, str] | None = None,
    threads: int = 1,
    direct_reads: str = DIRECT_READS,
    timeout: int = 900,
) -> dict[str, str | float | int]:
    log_path = run_dir / f"{experiment}__{variant.key}.log"
    source = variant.source_path(distribution="random")
    if not source.exists():
        raise FileNotFoundError(f"Missing source DB: {source}")

    db_path = source
    work_db = run_dir / "workdb" / f"{experiment}__{variant.key}"
    if not read_only:
        if work_db.exists():
            shutil.rmtree(work_db)
        work_db.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(source, work_db)
        db_path = work_db

    props = {
        "rocksdb.dbname": str(db_path),
        "rocksdb.use_direct_reads": direct_reads,
        "status.interval": "30",
    }
    if variant.lorc:
        props["rocksdb.lorc_enable_stats"] = "true"
    if read_only:
        props.update(
            {
                "rocksdb.disable_auto_compactions": "true",
                "rocksdb.create_if_missing": "false",
                "rocksdb.destroy": "false",
                "rocksdb.read_only": "true",
            }
        )
    if extra_props:
        props.update(extra_props)

    cmd = [
        "./ycsb",
        "-run",
        "-db",
        YCSB_DB,
        "-P",
        str(workload),
        "-P",
        str(ROOT / YCSB_DB / variant.prop_file),
    ]
    for key, value in props.items():
        cmd.extend(["-p", f"{key}={value}"])
    cmd.extend(["-threads", str(threads), "-s"])

    header = [
        f"===== START {experiment} {variant.label} {datetime.now(timezone.utc).isoformat()} =====",
        f"Command: {shell_quote(cmd)}",
        f"read_only={read_only}",
        f"db_path={db_path}",
        "",
    ]
    print(f"[run] {experiment:22s} {variant.label:13s} -> {log_path.name}", flush=True)
    proc = subprocess.run(
        cmd,
        cwd=ROOT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        timeout=timeout,
    )
    footer = [
        "",
        f"===== END {experiment} {variant.label} rc={proc.returncode} {datetime.now(timezone.utc).isoformat()} =====",
    ]
    text = "\n".join(header) + proc.stdout + "\n".join(footer) + "\n"
    log_path.write_text(text, errors="replace")

    row: dict[str, str | float | int] = {
        "experiment": experiment,
        "variant": variant.label,
        "variant_key": variant.key,
        "db": variant.db,
        "lorc": int(variant.lorc),
        "log": str(log_path),
        "returncode": proc.returncode,
        "threads": threads,
        "direct_reads": direct_reads,
    }
    row.update(parse_log(text))
    if not read_only and work_db.exists():
        shutil.rmtree(work_db)
    return row


def build_matrix(workload_dir: Path) -> list[dict]:
    runs: list[dict] = []

    def add(
        experiment: str,
        variants: list[Variant],
        measured_ops: int,
        *,
        hot_ratio: float = 0.05,
        read_prop: float = 0.0,
        update_prop: float = 0.0,
        scan_prop: float = 1.0,
        requestdistribution: str = "zipfian",
        scan_length: int = 20,
        distribution_tag: str = "random",
        extra_props: dict[str, str] | None = None,
        min_warmup_ops: int = 50_000,
        coverage_factor: float = 2.0,
        threads: int = 1,
        direct_reads: str = DIRECT_READS,
        phased_ranges: str | None = None,
        timeout: int = 900,
    ) -> None:
        read_only = update_prop == 0.0
        name = (
            f"{experiment}_scan{scan_length}_hot{hot_ratio:g}_"
            f"scanp{scan_prop:g}_upd{update_prop:g}_{requestdistribution}"
        ).replace(".", "p")
        workload, total_ops, warmup_ops, warmup_ratio = make_workload(
            workload_dir,
            name,
            measured_ops=measured_ops,
            hot_ratio=hot_ratio,
            read_prop=read_prop,
            update_prop=update_prop,
            scan_prop=scan_prop,
            distribution=requestdistribution,
            scan_length=scan_length,
            min_warmup_ops=min_warmup_ops,
            coverage_factor=coverage_factor,
            phased_ranges=phased_ranges,
        )
        for variant in variants:
            runs.append(
                {
                    "experiment": experiment,
                    "workload": workload,
                    "variant": variant,
                    "distribution_tag": distribution_tag,
                    "read_only": read_only,
                    "extra_props": extra_props or {},
                    "recordcount": RECORDCOUNT,
                    "operationcount": total_ops,
                    "warmup_ops": warmup_ops,
                    "warmup_ratio": warmup_ratio,
                    "hot_ratio": hot_ratio,
                    "read_prop": read_prop,
                    "update_prop": update_prop,
                    "scan_prop": scan_prop,
                    "requestdistribution": requestdistribution,
                    "scan_length": scan_length,
                    "threads": threads,
                    "direct_reads": direct_reads,
                    "timeout": timeout,
                }
            )

    add("main_hot_scan", VARIANTS, 500_000, min_warmup_ops=100_000, coverage_factor=10.0)

    for scan_length in [5, 20, 50, 100]:
        add(
            f"scan_length_{scan_length}",
            VARIANTS,
            120_000,
            scan_length=scan_length,
            min_warmup_ops=100_000,
            coverage_factor=10.0,
        )

    for hot_ratio in [0.01, 0.05, 0.10]:
        add(
            f"hot_ratio_{int(hot_ratio * 100)}",
            VARIANTS,
            120_000,
            hot_ratio=hot_ratio,
            min_warmup_ops=100_000,
            coverage_factor=10.0,
        )

    lorc_variants = [v for v in VARIANTS if v.lorc]
    for mb in [64, 128, 256, 512, 1024]:
        add(
            f"cache_size_{mb}mb",
            lorc_variants,
            15_000,
            hot_ratio=0.10,
            scan_length=50,
            extra_props={"rocksdb.range_cache_size": str(mb * 1024 * 1024)},
            min_warmup_ops=30_000,
            coverage_factor=1.0,
        )

    for scan_prop in [1.0, 0.5, 0.1]:
        add(
            f"mix_scan_{int(scan_prop * 100)}",
            VARIANTS,
            150_000,
            read_prop=1.0 - scan_prop,
            scan_prop=scan_prop,
            min_warmup_ops=100_000,
            coverage_factor=8.0,
        )

    for dist in ["zipfian", "uniform"]:
        add(f"distribution_{dist}", VARIANTS, 100_000, requestdistribution=dist)

    add(
        "update_scan",
        VARIANTS,
        60_000,
        read_prop=0.45,
        update_prop=0.05,
        scan_prop=0.50,
        scan_length=20,
        min_warmup_ops=80_000,
        coverage_factor=4.0,
    )

    add(
        "direct_reads_on",
        VARIANTS[:2],
        20_000,
        hot_ratio=0.01,
        scan_length=20,
        min_warmup_ops=30_000,
        coverage_factor=4.0,
        direct_reads="true",
        timeout=1200,
    )

    return runs


def write_summary(rows: list[dict], path: Path) -> None:
    keys = [
        "experiment",
        "variant",
        "db",
        "lorc",
        "returncode",
        "throughputops/sec",
        "scan_count",
        "scan_avg_us",
        "scan_p99_us",
        "scan_p999_us",
        "read_count",
        "read_avg_us",
        "read_p99_us",
        "update_count",
        "update_avg_us",
        "update_p99_us",
        "scan_length",
        "hot_ratio",
        "scan_prop",
        "read_prop",
        "update_prop",
        "requestdistribution",
        "threads",
        "direct_reads",
        "experiment_cache_mb",
        "lorc_current_size",
        "lorc_capacity",
        "lorc_total_range_length",
        "lorc_materialized_entries",
        "lorc_materialized_key_bytes",
        "lorc_materialized_value_bytes",
        "lorc_full_hit_rate",
        "lorc_hit_size_rate",
        "lorc_put_range_num",
        "lorc_avg_put_range_us",
        "lorc_get_range_num",
        "lorc_avg_get_range_us",
        "operationcount",
        "warmup_ops",
        "log",
    ]
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)


def load_rows(path: Path) -> list[dict[str, str]]:
    with path.open() as f:
        return list(csv.DictReader(f))


def f(row: dict, key: str, default: float = float("nan")) -> float:
    try:
        value = row.get(key, "")
        if value == "":
            return default
        return float(value)
    except (TypeError, ValueError):
        return default


def select(rows: list[dict], prefix: str | None = None, experiment: str | None = None) -> list[dict]:
    if experiment is not None:
        return [r for r in rows if r["experiment"] == experiment]
    assert prefix is not None
    return [r for r in rows if r["experiment"].startswith(prefix)]


def style() -> None:
    plt.rcParams.update(
        {
            "font.size": 9,
            "axes.titlesize": 10,
            "axes.labelsize": 9,
            "legend.fontsize": 8,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "figure.dpi": 160,
            "savefig.bbox": "tight",
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )


COLORS = {
    "RocksDB": "#4E79A7",
    "RocksDB+LORC": "#F28E2B",
    "BlobDB": "#59A14F",
    "BlobDB+LORC": "#E15759",
}


def bar(ax, labels, values, ylabel, title=None, log=False):
    colors = [COLORS.get(label, "#777777") for label in labels]
    ax.bar(labels, values, color=colors, edgecolor="#303030", linewidth=0.5)
    ax.set_ylabel(ylabel)
    if title:
        ax.set_title(title)
    if log:
        ax.set_yscale("log")
    ax.grid(axis="y", color="#dddddd", linewidth=0.6, alpha=0.8)
    ax.set_axisbelow(True)
    ax.tick_params(axis="x", rotation=18)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:,.0f}"))


def line_by_variant(ax, rows, xkey, ykey, ylabel, xlabel, title=None, log=False):
    for label in [v.label for v in VARIANTS]:
        sub = sorted([r for r in rows if r["variant"] == label], key=lambda r: f(r, xkey))
        if not sub:
            continue
        ax.plot(
            [f(r, xkey) for r in sub],
            [f(r, ykey) for r in sub],
            marker="o",
            linewidth=1.8,
            label=label,
            color=COLORS.get(label),
        )
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    if title:
        ax.set_title(title)
    if log:
        ax.set_yscale("log")
    ax.grid(True, color="#dddddd", linewidth=0.6, alpha=0.8)
    ax.set_axisbelow(True)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:,.0f}"))
    handles, labels = ax.get_legend_handles_labels()
    if handles:
        ax.legend(
            handles,
            labels,
            frameon=False,
            ncol=2,
            loc="upper center",
            bbox_to_anchor=(0.5, 1.30),
            handlelength=1.6,
            columnspacing=1.2,
        )


def grouped_bar(ax, rows, xkey, ykey, ylabel, xlabel=None):
    groups = list(dict.fromkeys(r[xkey] for r in rows))
    variants = [v.label for v in VARIANTS if any(r["variant"] == v.label for r in rows)]
    width = 0.18
    centers = list(range(len(groups)))
    offsets = [(i - (len(variants) - 1) / 2) * width for i in range(len(variants))]
    for off, variant in zip(offsets, variants):
        values = []
        for group in groups:
            match = next((r for r in rows if r[xkey] == group and r["variant"] == variant), None)
            values.append(f(match, ykey) if match else float("nan"))
        ax.bar(
            [c + off for c in centers],
            values,
            width=width,
            label=variant,
            color=COLORS.get(variant),
            edgecolor="#303030",
            linewidth=0.45,
        )
    ax.set_xticks(centers)
    ax.set_xticklabels(groups)
    if xlabel:
        ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.grid(axis="y", color="#dddddd", linewidth=0.6, alpha=0.8)
    ax.set_axisbelow(True)
    ax.yaxis.set_major_formatter(FuncFormatter(lambda x, _: f"{x:,.0f}"))
    ax.legend(
        frameon=False,
        ncol=2,
        loc="upper center",
        bbox_to_anchor=(0.5, 1.30),
        handlelength=1.6,
        columnspacing=1.2,
    )


def generate_figures(summary: Path, fig_dir: Path) -> list[Path]:
    rows = load_rows(summary)
    style()
    fig_dir.mkdir(parents=True, exist_ok=True)
    figs: list[Path] = []

    def save(name: str) -> None:
        out = fig_dir / name
        plt.savefig(out)
        figs.append(out)
        plt.close()

    main = select(rows, experiment="main_hot_scan")
    labels = [r["variant"] for r in main]
    throughput = [f(r, "throughputops/sec") for r in main]
    plt.figure(figsize=(3.45, 2.25))
    bar(plt.gca(), labels, throughput, "Throughput (ops/s)")
    save("eval_main_hot_scan_throughput.pdf")

    plt.figure(figsize=(3.45, 2.25))
    bar(plt.gca(), labels, [f(r, "scan_avg_us") for r in main], "Avg scan latency (us)")
    save("eval_main_avg_latency.pdf")

    plt.figure(figsize=(3.45, 2.25))
    bar(plt.gca(), labels, [f(r, "scan_p99_us") for r in main], "p99 scan latency (us)")
    save("eval_main_p99_latency.pdf")

    base = {r["db"]: f(r, "throughputops/sec") for r in main if r["lorc"] == "0"}
    speed_rows = [r for r in main if r["lorc"] == "1"]
    plt.figure(figsize=(3.45, 2.25))
    bar(
        plt.gca(),
        [r["variant"] for r in speed_rows],
        [f(r, "throughputops/sec") / base.get(r["db"], float("nan")) for r in speed_rows],
        "Speedup over native engine",
    )
    save("eval_main_speedup.pdf")

    scan_rows = select(rows, prefix="scan_length_")
    plt.figure(figsize=(3.45, 2.45))
    grouped_bar(plt.gca(), scan_rows, "scan_length", "throughputops/sec", "Throughput (ops/s)", "Scan length")
    save("eval_scan_length_throughput.pdf")

    plt.figure(figsize=(3.45, 2.45))
    grouped_bar(plt.gca(), scan_rows, "scan_length", "scan_p99_us", "p99 scan latency (us)", "Scan length")
    save("eval_scan_length_p99.pdf")

    hot_rows = select(rows, prefix="hot_ratio_")
    plt.figure(figsize=(3.45, 2.45))
    grouped_bar(plt.gca(), hot_rows, "hot_ratio", "throughputops/sec", "Throughput (ops/s)", "Hot-region ratio")
    save("eval_hot_ratio_throughput.pdf")

    plt.figure(figsize=(3.45, 2.45))
    grouped_bar(plt.gca(), hot_rows, "hot_ratio", "scan_p99_us", "p99 scan latency (us)", "Hot-region ratio")
    save("eval_hot_ratio_p99.pdf")

    cache_rows = select(rows, prefix="cache_size_")
    plt.figure(figsize=(3.45, 2.45))
    line_by_variant(plt.gca(), cache_rows, "experiment_cache_mb", "throughputops/sec", "Throughput (ops/s)", "Range cache size (MB)")
    save("eval_cache_size_throughput.pdf")

    plt.figure(figsize=(3.45, 2.45))
    line_by_variant(plt.gca(), cache_rows, "experiment_cache_mb", "scan_p99_us", "p99 scan latency (us)", "Range cache size (MB)", log=True)
    save("eval_cache_size_p99.pdf")

    plt.figure(figsize=(3.45, 2.45))
    ax = plt.gca()
    for label in [v.label for v in VARIANTS if v.lorc]:
        sub = sorted([r for r in cache_rows if r["variant"] == label], key=lambda r: f(r, "experiment_cache_mb"))
        if not sub:
            continue
        ax.plot(
            [f(r, "experiment_cache_mb") for r in sub],
            [100.0 * f(r, "lorc_hit_size_rate") for r in sub],
            marker="o",
            linewidth=1.8,
            label=label,
            color=COLORS.get(label),
        )
    ax.set_xlabel("Range cache size (MB)")
    ax.set_ylabel("Hit-record rate (%)")
