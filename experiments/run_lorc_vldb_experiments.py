def annotate_rows(rows: list[dict]) -> None:
    for row in rows:
        exp = str(row["experiment"])
        m = re.search(r"cache_size_(\d+)mb", exp)
        row["experiment_cache_mb"] = int(m.group(1)) if m else ""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--stamp", default=datetime.now().strftime("%Y%m%d-%H%M%S"))
    parser.add_argument("--skip-run", action="store_true")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--summary", type=Path)
    parser.add_argument("--max-runs", type=int, default=0)
    args = parser.parse_args()

    run_dir = ROOT / "result" / "log" / "vldb" / args.stamp
    workload_dir = run_dir / "workloads"
    fig_dir = PAPER / "figures" / "experiments"
    run_dir.mkdir(parents=True, exist_ok=True)
    workload_dir.mkdir(parents=True, exist_ok=True)

    if args.skip_run:
        if not args.summary:
            print("--skip-run requires --summary", file=sys.stderr)
            return 2
        figs = generate_figures(args.summary, fig_dir)
        print(f"Generated {len(figs)} figures in {fig_dir}")
        return 0

    matrix = build_matrix(workload_dir)
    if args.max_runs:
        matrix = matrix[: args.max_runs]

    rows: list[dict] = []
    completed: set[tuple[str, str]] = set()
    summary = run_dir / "summary.csv"
    if args.resume and summary.exists():
        rows = [dict(r) for r in load_rows(summary)]
        completed = {
            (str(r.get("experiment")), str(r.get("variant")))
            for r in rows
            if str(r.get("returncode")) == "0"
        }
        print(f"Resuming from {summary}: {len(completed)} completed runs", flush=True)
    for i, item in enumerate(matrix, 1):
        run_key = (item["experiment"], item["variant"].label)
        if run_key in completed:
            print(f"=== {i}/{len(matrix)} skip completed {run_key[0]} {run_key[1]} ===", flush=True)
            continue
        print(f"=== {i}/{len(matrix)} ===", flush=True)
        row = run_one(
            run_dir=run_dir,
            workload=item["workload"],
            variant=item["variant"],
            experiment=item["experiment"],
            distribution=item["distribution_tag"],
            read_only=item["read_only"],
            extra_props=item["extra_props"],
            threads=item["threads"],
            direct_reads=item["direct_reads"],
            timeout=item["timeout"],
        )
        row.update(
            {
                "recordcount": item["recordcount"],
                "operationcount": item["operationcount"],
                "warmup_ops": item["warmup_ops"],
                "warmup_ratio": item["warmup_ratio"],
                "hot_ratio": item["hot_ratio"],
                "read_prop": item["read_prop"],
                "update_prop": item["update_prop"],
                "scan_prop": item["scan_prop"],
                "requestdistribution": item["requestdistribution"],
                "scan_length": item["scan_length"],
                "threads": item["threads"],
                "direct_reads": item["direct_reads"],
            }
        )
        rows.append(row)
        annotate_rows(rows)
        write_summary(rows, summary)

    figs = generate_figures(summary, fig_dir)
    print(f"Summary: {summary}")
    print(f"Figures: {fig_dir}")
    for fig in figs:
        print(f"  {fig}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
