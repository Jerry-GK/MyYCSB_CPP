#!/usr/bin/env python3
"""Run the in-engine skip-list range cache baseline against LORC."""

from __future__ import annotations

import csv
import math
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parents[1]
PAPER = ROOT.parent / "68368b2dccae04737d71ce11"
SOURCE_DB = (
    ROOT
    / "db"
    / "ycsb-source-24B-16B-representation"
    / "ycsb-rocksdb-source-24B-16B-representation-random"
)
SUMMARY = PAPER / "figures" / "experiments" / "lorc_skiplist_ycsb_summary.csv"
FIGURE = PAPER / "figures" / "experiments" / "eval_representation_probe.pdf"

RECORDCOUNT = 1_048_576
FIELDLENGTH = 16
CACHE_BUDGET = 128 * 1024 * 1024
HOT_RATIO = 0.02
SCAN_LENGTHS = [1, 10, 100, 1000, 10000]
MEASURED_ENTRY_TARGET = 10_000_000
MAX_MEASURED_OPS = 50_000
MIN_MEASURED_OPS = 500
WARMUP_COVERAGE_FACTOR = 20.0
MIN_WARMUP_OPS = 500

THROUGHPUT_RE = re.compile(r"Run measured throughput\(ops/sec\):\s*([0-9.]+)")
LORC_RE = re.compile(r"\[LORC_STATS\]\s+(?P<body>.*)")


@dataclass(frozen=True)
class Variant:
    label: str
    backend: str
    color: str
    marker: str


VARIANTS = [
    Variant("Entry skip-list range cache", "skiplist", "#8C6D31", "o"),
    Variant("LORC continuous segment", "lorc", "#3D8B5B", "^"),
]


def measured_ops(scan_length: int) -> int:
    return max(
        MIN_MEASURED_OPS,
        min(MAX_MEASURED_OPS, math.ceil(MEASURED_ENTRY_TARGET / scan_length)),
    )


def warmup_ops(scan_length: int) -> int:
    hot_records = RECORDCOUNT * HOT_RATIO
    coverage_ops = math.ceil(WARMUP_COVERAGE_FACTOR * hot_records / scan_length)
    return max(MIN_WARMUP_OPS, coverage_ops)


def workload_text(scan_length: int, warmup: int) -> str:
    ops = measured_ops(scan_length)
    total_ops = warmup + ops
    return f"""# Generated by experiments/run_skiplist_range_cache_ycsb.py
recordcount={RECORDCOUNT}
operationcount={total_ops}
hot_data_ratio={HOT_RATIO}
warmup_ratio={warmup / total_ops:.8f}
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

zeropadding=24
fieldcount=1
fieldlength={FIELDLENGTH}

readallfields=true
writeallfields=true

readproportion=0
updateproportion=0
scanproportion=1
insertproportion=0

requestdistribution=zipfian

minscanlength={scan_length}
maxscanlength={scan_length}
warmupscanlength={scan_length}
scanlengthdistribution=uniform
"""


def props_text(backend: str) -> str:
    return f"""rocksdb.dbname={SOURCE_DB}
rocksdb.destroy=false
rocksdb.create_if_missing=false
rocksdb.read_only=true
rocksdb.disable_auto_compactions=true
rocksdb.disableWAL=true
rocksdb.enable_blob_files=false

rocksdb.block_cache_size=0
rocksdb.blob_cache_size=0
rocksdb.range_cache_size={CACHE_BUDGET}
rocksdb.range_cache_backend={backend}
rocksdb.range_cache_physical_type=continuous
rocksdb.range_cache_victim_policy=boundary_lru
rocksdb.lorc_enable_stats=true

rocksdb.compression=no
rocksdb.use_direct_reads=false
rocksdb.reuse_scan_buffers=true
ycsb.perf_l1d=false
"""


def load_workload_text() -> str:
    return f"""# Generated 16B-value source DB for representation experiment.
recordcount={RECORDCOUNT}
operationcount={RECORDCOUNT}
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

zeropadding=24
fieldcount=1
fieldlength={FIELDLENGTH}

readallfields=true
writeallfields=true

readproportion=0
updateproportion=0
scanproportion=0
insertproportion=1

requestdistribution=uniform
"""


def load_props_text() -> str:
    return f"""rocksdb.dbname={SOURCE_DB}
rocksdb.destroy=false
rocksdb.create_if_missing=true
rocksdb.read_only=false
rocksdb.disable_auto_compactions=false
rocksdb.disableWAL=false
rocksdb.enable_blob_files=false

rocksdb.block_cache_size={CACHE_BUDGET}
rocksdb.blob_cache_size=0
rocksdb.range_cache_size=0

rocksdb.compression=no
rocksdb.use_direct_reads=false
"""


def ensure_source_db() -> None:
    if SOURCE_DB.exists():
        return
    print(f"building {FIELDLENGTH}B representation source DB at {SOURCE_DB}", flush=True)
    SOURCE_DB.parent.mkdir(parents=True, exist_ok=True)
    shutil.rmtree(SOURCE_DB, ignore_errors=True)
    with tempfile.TemporaryDirectory(prefix="lorc-repr-load-") as tmp:
        workload = Path(tmp) / "load_workload.properties"
        props = Path(tmp) / "load_rocksdb.properties"
        workload.write_text(load_workload_text())
        props.write_text(load_props_text())
        cmd = [
            str(ROOT / "ycsb"),
            "-load",
            "-db",
            "rocksdb_lorc",
            "-P",
            str(workload),
            "-P",
            str(props),
        ]
        subprocess.run(
            cmd,
            cwd=ROOT,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=True,
        )


def parse_lorc_stats(text: str) -> dict[str, str]:
    match = LORC_RE.search(text)
    if not match:
        return {}
    result: dict[str, str] = {}
    for token in match.group("body").split():
        if "=" in token:
            k, v = token.split("=", 1)
            result[k] = v
    return result


def run_case(variant: Variant, scan_length: int) -> dict[str, object]:
    warmup = warmup_ops(scan_length)
    with tempfile.TemporaryDirectory(prefix="lorc-skiplist-ycsb-") as tmp:
        workload = Path(tmp) / "workload.properties"
        props = Path(tmp) / "rocksdb.properties"
        workload.write_text(workload_text(scan_length, warmup))
        props.write_text(props_text(variant.backend))
        cmd = [
            str(ROOT / "ycsb"),
            "-run",
            "-db",
            "rocksdb_lorc",
            "-P",
            str(workload),
            "-P",
            str(props),
        ]
        proc = subprocess.run(
            cmd,
            cwd=ROOT,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=True,
        )
    output = proc.stdout
    throughput_match = THROUGHPUT_RE.search(output)
    if throughput_match is None:
        raise RuntimeError(
            f"Failed to parse throughput output for "
            f"{variant.label} len={scan_length}\\n{output[-2000:]}"
        )
    lorc_stats = parse_lorc_stats(output)
    return {
        "variant": variant.label,
        "backend": variant.backend,
        "scan_length": scan_length,
        "warmup_ops": warmup,
        "measured_ops": measured_ops(scan_length),
        "throughput_ops_sec": float(throughput_match.group(1)),
        "mean_scan_latency_us": round(1_000_000.0 / float(throughput_match.group(1)), 3),
        "returned_records_per_sec": round(float(throughput_match.group(1)) * scan_length, 3),
        "full_hit_rate": float(lorc_stats.get("full_hit_rate", 0)),
        "hit_size_rate": float(lorc_stats.get("hit_size_rate", 0)),
        "current_size": int(float(lorc_stats.get("current_size", 0))),
        "total_range_length": int(float(lorc_stats.get("total_range_length", 0))),
    }


def plot(rows: list[dict[str, object]]) -> None:
    plt.rcParams.update(
        {
            "font.size": 8.4,
            "axes.labelsize": 8.4,
            "legend.fontsize": 8,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "figure.dpi": 180,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )
    fig, ax = plt.subplots(1, 1, figsize=(3.8, 2.45), constrained_layout=True)
    for variant in VARIANTS:
        data = [r for r in rows if r["variant"] == variant.label]
        data.sort(key=lambda r: int(r["scan_length"]))
        xs = [int(r["scan_length"]) for r in data]
        ys = [float(r["returned_records_per_sec"]) for r in data]
        ax.plot(
            xs,
            ys,
            marker=variant.marker,
            linewidth=1.8,
            markersize=4.5,
            color=variant.color,
            label=variant.label.replace(" range cache", ""),
        )
    ax.set_xscale("log")
    ax.set_xticks(SCAN_LENGTHS)
    ax.get_xaxis().set_major_formatter(lambda x, _pos: f"{int(x)}")
    ax.set_xlabel("Scan length")
    ax.set_ylabel("Returned records/s")
    ax.yaxis.set_major_formatter(lambda y, _pos: f"{y / 1e6:.1f}M")
    ax.grid(axis="y", color="#E7E7E7", linewidth=0.65)
    legend = ax.legend(frameon=True, loc="best")
    legend.get_frame().set_linewidth(0)
    legend.get_frame().set_alpha(0.9)
    FIGURE.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGURE, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    ensure_source_db()
    rows = []
    for scan_length in SCAN_LENGTHS:
        for variant in VARIANTS:
            print(f"running {variant.label} scan_length={scan_length}", flush=True)
            row = run_case(variant, scan_length)
            print(row, flush=True)
            rows.append(row)
    SUMMARY.parent.mkdir(parents=True, exist_ok=True)
    with SUMMARY.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    plot(rows)
    print(f"summary={SUMMARY}")
    print(f"figure={FIGURE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
