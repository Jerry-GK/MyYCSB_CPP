#!/usr/bin/env python3
"""Run actual YCSB cache-pressure runs for LORC victim policies.

This is an end-to-end counterpart to the small structural policy probe. It
uses a real RocksDB source database, randomized scan warmup, and measured
scan-only YCSB operations. The key metric is storage-touch scan ratio, computed
as 1 - LORC full-hit rate. A non-full cache hit means the scan opened the
lower-tier storage path for at least one gap.
"""

from __future__ import annotations

import argparse
import csv
import shutil
from datetime import datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

import run_lorc_fair_matrix as fair


ROOT = fair.ROOT
PAPER = fair.PAPER
MB = fair.MB

POLICIES = [
    ("boundary_lru", "Boundary-LRU"),
    ("physical_lru", "Physical LRU"),
    ("shortest_range", "Shortest-range"),
]


def as_float(row: dict[str, str], key: str, default: float = 0.0) -> float:
    try:
        value = row.get(key, "")
        return default if value == "" else float(value)
    except (TypeError, ValueError):
        return default


def lru_pressure_workload_text(
    *,
    dataset: fair.Dataset,
    scan_length: int,
    warmup_old_ops: int,
    warmup_refresh_ops: int,
    warmup_new_ops: int,
    measured_old_ops: int,
    measured_new_ops: int,
) -> str:
    warmup_ops = warmup_old_ops + warmup_refresh_ops + warmup_new_ops
    measured_ops = measured_old_ops + measured_new_ops
    total_ops = warmup_ops + measured_ops
    old_start = 0
    old_end = 96_000 - scan_length
    refresh_start = 38_000
    refresh_end = 56_000
    new_start = 1_000_000
    new_end = 1_048_000 - scan_length
    phases = [
        f"{old_start}:{old_end}:{warmup_old_ops}",
        f"{refresh_start}:{refresh_end}:{warmup_refresh_ops}",
        f"{new_start}:{new_end}:{warmup_new_ops}",
        f"{refresh_start}:{refresh_end}:{measured_old_ops}",
        f"{new_start}:{new_end}:{measured_new_ops}",
    ]
    return f"""# Generated by experiments/run_lorc_lru_actual.py
recordcount={dataset.recordcount}
operationcount={total_ops}
warmup_ratio={warmup_ops / total_ops:.8f}
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

zeropadding=24
fieldcount=1
fieldlength={dataset.fieldlength}

readallfields=true
writeallfields=true

readproportion=0
updateproportion=0
scanproportion=1
insertproportion=0

requestdistribution=phased
phased_ranges={";".join(phases)}

minscanlength={scan_length}
maxscanlength={scan_length}
scanlengthdistribution=uniform
"""


def run_experiment(
    *,
    out_dir: Path,
    budgets_mb: list[int],
    reload_source: bool,
) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    dataset = fair.GENERAL_DATASET
    fair.prepare_sources(
        [dataset],
        budget=fair.DEFAULT_CACHE_BUDGET,
        out_dir=out_dir,
        reload=reload_source,
    )

    workload_dir = out_dir / "workloads"
    workload_dir.mkdir(parents=True, exist_ok=True)
    variant = fair.VARIANTS[1]  # RocksDB+LORC
    rows: list[dict[str, str | int | float]] = []

    scan_length = 1024
    warmup_old_ops = 1200
    warmup_refresh_ops = 600
    warmup_new_ops = 700
    measured_old_ops = 3000
    measured_new_ops = 1500
    warmup_ops = warmup_old_ops + warmup_refresh_ops + warmup_new_ops
    measured_ops = measured_old_ops + measured_new_ops

    for budget_mb in budgets_mb:
        budget = budget_mb * MB
        workload = workload_dir / f"lru_actual_phased_{budget_mb}mb.properties"
        workload.write_text(
            lru_pressure_workload_text(
                dataset=dataset,
                scan_length=scan_length,
                warmup_old_ops=warmup_old_ops,
                warmup_refresh_ops=warmup_refresh_ops,
                warmup_new_ops=warmup_new_ops,
                measured_old_ops=measured_old_ops,
                measured_new_ops=measured_new_ops,
            )
        )
        op_count = warmup_ops + measured_ops
        warmup_ratio = warmup_ops / op_count
        source = dataset.source_path("rocksdb")
        if not source.exists():
            raise FileNotFoundError(source)

        for policy_name, policy_label in POLICIES:
            work_db = out_dir / "workdb" / f"lru_{budget_mb}mb_{policy_name}"
            if work_db.exists():
                shutil.rmtree(work_db)
            work_db.parent.mkdir(parents=True, exist_ok=True)
            # Copy even though the workload is read-only so every policy starts
            # from the same clean source and can be inspected independently.
            shutil.copytree(source, work_db)

            props = fair.system_props(variant, budget, direct_reads="false")
            props.update(fair.read_only_props(variant))
            props["rocksdb.range_cache_victim_policy"] = policy_name
            props["rocksdb.lorc_enable_stats"] = "true"

            log_name = f"lru_actual__{budget_mb}mb__{policy_name}"
            rc, text, time_info = fair.run_ycsb(
                mode="run",
                variant=variant,
                workload=workload,
                db_path=work_db,
                run_dir=out_dir,
                log_name=log_name,
                props=props,
                threads=1,
                timeout=2400,
                random_seed=41 + budget_mb,
            )
            shutil.rmtree(work_db)
            parsed = fair.parse_log(text)
            if rc != 0:
                raise RuntimeError(f"Run failed for {policy_name}/{budget_mb}MB\n{text[-2500:]}")

            full_hit = float(parsed.get("lorc_full_hit_rate", 0.0))
            hit_size = float(parsed.get("lorc_hit_size_rate", 0.0))
            row: dict[str, str | int | float] = {
                "budget_mb": budget_mb,
                "policy": policy_name,
                "policy_label": policy_label,
                "dataset": dataset.name,
                "recordcount": dataset.recordcount,
                "fieldlength": dataset.fieldlength,
                "scan_length": scan_length,
                "hot_ratio": "",
                "operationcount": op_count,
                "measured_ops": measured_ops,
                "warmup_ops": warmup_ops,
                "warmup_ratio": warmup_ratio,
                "warmup_old_ops": warmup_old_ops,
                "warmup_refresh_ops": warmup_refresh_ops,
                "warmup_new_ops": warmup_new_ops,
                "measured_old_ops": measured_old_ops,
                "measured_new_ops": measured_new_ops,
                "cache_budget_bytes": budget,
                "throughput_ops_sec": float(parsed.get("throughputops/sec", 0.0)),
                "scan_avg_us": float(parsed.get("scan_avg_us", 0.0)),
                "scan_p99_us": float(parsed.get("scan_p99_us", 0.0)),
                "lorc_full_hit_rate": full_hit,
                "storage_touch_scan_ratio": max(0.0, 1.0 - full_hit),
                "lorc_hit_size_rate": hit_size,
                "lorc_current_size": float(parsed.get("lorc_current_size", 0.0)),
                "lorc_capacity": float(parsed.get("lorc_capacity", 0.0)),
                "lorc_total_range_length": float(parsed.get("lorc_total_range_length", 0.0)),
                "lorc_materialized_entries": float(parsed.get("lorc_materialized_entries", 0.0)),
                "max_rss_kb": int(time_info.get("max_rss_kb", 0)),
                "fs_inputs": int(time_info.get("fs_inputs", 0)),
                "fs_outputs": int(time_info.get("fs_outputs", 0)),
                "log": str(out_dir / f"{log_name}.log"),
            }
            rows.append(row)

    summary = out_dir / "lorc_lru_actual_summary.csv"
    with summary.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return summary


def plot(summary: Path, figure: Path) -> None:
    with summary.open() as f:
        rows = list(csv.DictReader(f))

    by_budget = sorted({int(r["budget_mb"]) for r in rows})
    by_policy = {p: label for p, label in POLICIES}
    index = {(int(r["budget_mb"]), r["policy"]): r for r in rows}

    plt.rcParams.update(
        {
            "font.size": 8.4,
            "axes.labelsize": 8.4,
            "legend.fontsize": 8,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "figure.dpi": 180,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )
    colors = ["#3B6EA8", "#C84E4E", "#5D9A55"]
    hatches = ["", "///", "..."]
    metrics = [
        ("Storage-touch scans", "storage_touch_scan_ratio", "%", lambda v: 100 * v),
        ("Throughput", "throughput_ops_sec", "K scans/s", lambda v: v / 1000.0),
        ("p99 latency", "scan_p99_us", "us", lambda v: v),
    ]
    fig, axes = plt.subplots(1, 3, figsize=(7.35, 2.35), constrained_layout=True)
    width = 0.24
    xs = list(range(len(by_budget)))
    for ax, (title, key, ylabel, transform) in zip(axes, metrics):
        for i, (policy, label) in enumerate(POLICIES):
            values = [
                transform(as_float(index[(budget, policy)], key))
                for budget in by_budget
            ]
            offset = (i - 1) * width
            bars = ax.bar(
                [x + offset for x in xs],
                values,
                width,
                label=label,
                color=colors[i],
                edgecolor="#222222",
                linewidth=0.45,
            )
            for bar in bars:
                bar.set_hatch(hatches[i])
        ax.set_title(title)
        ax.set_ylabel(ylabel)
        ax.set_xticks(xs)
        ax.set_xticklabels([f"{b}MB" for b in by_budget])
        ax.grid(axis="y", color="#E7E7E7", linewidth=0.65)
        ax.set_axisbelow(True)
    axes[0].set_ylim(0, 100)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.06),
        ncol=3,
        frameon=False,
        columnspacing=1.0,
        handlelength=1.3,
    )
    figure.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(figure, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--summary", type=Path)
    parser.add_argument("--plot-only", action="store_true")
    parser.add_argument("--reload-source", action="store_true")
    parser.add_argument("--budgets-mb", default="64,128")
    args = parser.parse_args()

    out_dir = args.out or (ROOT / "result" / "log" / f"lorc_lru_actual_{datetime.now().strftime('%Y%m%d_%H%M%S')}")
    figure = PAPER / "figures" / "experiments" / "eval_lru_policy_actual.pdf"
    paper_summary = PAPER / "figures" / "experiments" / "lorc_lru_actual_summary.csv"

    if args.plot_only:
        if not args.summary:
            raise SystemExit("--plot-only requires --summary")
        plot(args.summary, figure)
        paper_summary.write_text(args.summary.read_text())
        print(f"summary={args.summary}")
        print(f"figure={figure}")
        return 0

    budgets = [int(x.strip()) for x in args.budgets_mb.split(",") if x.strip()]
    summary = run_experiment(
        out_dir=out_dir,
        budgets_mb=budgets,
        reload_source=args.reload_source,
    )
    plot(summary, figure)
    paper_summary.write_text(summary.read_text())
    print(f"summary={summary}")
    print(f"paper_summary={paper_summary}")
    print(f"figure={figure}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
