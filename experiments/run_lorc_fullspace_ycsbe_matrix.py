def run_seed(item: RunItem) -> int:
    # Keep the request stream identical across systems for the same experimental
    # point.  Cache experiments are very sensitive to the exact Zipfian prefix
    # covered during warmup, so the seed must not depend on the cache variant or
    # replacement policy.
    return 1 + (
        fair.zlib.crc32(
            (
                f"{item.suite}|{item.x_value}|{item.dataset.name}|"
                f"sl={item.scan_length}|zipf={item.zipfian_const}|"
                f"upd={item.update_prop}|threads={item.threads}|"
                f"cache={item.cache_budget_bytes}|ops={item.operationcount}|"
                f"warmup={item.warmup_ops}"
            ).encode("utf-8")
        )
        % 2_000_000_000
    )


def props_for(item: RunItem) -> dict[str, str]:
    props = fair.system_props(
        item.variant, item.cache_budget_bytes, direct_reads="false"
    )
    if item.read_only:
        props.update(fair.read_only_props(item.variant))
    elif item.variant.engine == "lsbm":
        props.update(
            {
                "leveldb.destroy": "false",
                "leveldb.run_compaction": "true",
                "leveldb.compaction_buffer_trim_interval": "30",
            }
        )
    else:
        props.update(
            {
                "rocksdb.disable_auto_compactions": "false",
                "rocksdb.create_if_missing": "false",
                "rocksdb.destroy": "false",
                "rocksdb.read_only": "false",
            }
        )
    if item.variant.engine == "lsbm":
        props["leveldb.deserialize_on_read"] = "true"
    else:
        props["rocksdb.deserialize_on_read"] = "true"
    if item.variant.lorc:
        props["rocksdb.range_cache_victim_policy"] = item.lru_policy
        props["rocksdb.lorc_point_expansion_entries"] = "0"
    if item.variant.label == "BlobDB+LORC" and item.dataset.fieldlength < 512:
        props["rocksdb.lorc_value_separation_aware"] = "false"
        props["rocksdb.lorc_bypass_lower_cache_on_refill"] = "false"
        props["rocksdb.lorc_min_materialized_value_bytes"] = "0"
    if item.single_thread_warmup:
        props["singlethreadwarmup"] = "true"
    return props


def prewarm_files(path: Path, warmed: set[Path]) -> None:
    resolved = path.resolve()
    if resolved in warmed:
        return
    if not resolved.exists():
        return
    print(f"[prewarm-files] {resolved}", flush=True)
    find = subprocess.Popen(
        ["find", str(resolved), "-type", "f", "-print0"],
        stdout=subprocess.PIPE,
    )
    cat = subprocess.run(
        ["xargs", "-0", "-r", "cat"],
        stdin=find.stdout,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        check=False,
    )
    if find.stdout is not None:
        find.stdout.close()
    find.wait()
    if find.returncode != 0 or cat.returncode != 0:
        raise RuntimeError(f"Failed to prewarm database files under {resolved}")
    warmed.add(resolved)


def execute_plan(
    plan: list[RunItem],
    *,
    out_dir: Path,
    max_runs: int | None,
    file_prewarm: bool,
) -> list[dict]:
    rows: list[dict] = []
    selected = plan if max_runs is None else plan[:max_runs]
    warmed_paths: set[Path] = set()
    for index, item in enumerate(selected, start=1):
        source = item.dataset.source_path(item.variant.engine)
        if not source.exists():
            raise FileNotFoundError(f"Missing source DB for {item.variant.label}: {source}")

        db_path = source
        work_db: Path | None = None
        if not item.read_only:
            work_db = (
                out_dir
                / "workdb"
                / f"{index:03d}__{item.suite}__{item.x_value}__{item.variant.key}"
            )
            if work_db.exists():
                shutil.rmtree(work_db)
            work_db.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(source, work_db)
            db_path = work_db

        if file_prewarm:
            prewarm_files(db_path, warmed_paths)

        props = props_for(item)
        log_name = f"{index:03d}__{item.suite}__{item.x_value}__{item.variant.key}"
        seed = run_seed(item)
        try:
            rc, text, time_info = fair.run_ycsb(
                mode="run",
                variant=item.variant,
                workload=item.workload,
                db_path=db_path,
                run_dir=out_dir,
                log_name=log_name,
                props=props,
                threads=item.threads,
                timeout=item.timeout,
                random_seed=seed,
            )
        finally:
            if work_db is not None and work_db.exists():
                shutil.rmtree(work_db)

        row: dict[str, str | int | float] = {
            "run_index": index,
            "suite": item.suite,
            "x_value": item.x_value,
            "x_label": item.x_label,
            "dataset": item.dataset.name,
            "recordcount": item.dataset.recordcount,
            "fieldlength": item.dataset.fieldlength,
            "variant": item.variant.label,
            "variant_key": item.variant.key,
            "engine": item.variant.engine,
            "returncode": rc,
            "read_only": int(item.read_only),
            "scan_length": item.scan_length,
            "zipfian_const": item.zipfian_const,
            "update_prop": item.update_prop,
            "scan_prop": item.scan_prop,
            "operationcount": item.operationcount,
            "warmup_ops": item.warmup_ops,
            "warmup_ratio": item.warmup_ratio,
            "cache_budget_bytes": item.cache_budget_bytes,
            "cache_budget_mb": item.cache_budget_bytes // MB,
            "threads": item.threads,
            "single_thread_warmup": int(item.single_thread_warmup),
            "lru_policy": item.lru_policy,
            "random_seed": seed,
            "log": str(out_dir / f"{log_name}.log"),
        }
        row.update(fair.parse_log(text))
        row.update(time_info)
        rows.append(row)
        write_summary(rows, out_dir / "summary_partial.csv")
        if rc != 0:
            raise RuntimeError(f"Run failed: {log_name}\n{text[-2500:]}")
    return rows


