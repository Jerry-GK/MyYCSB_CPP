def dataset_for_value_size(value_size: int) -> fair.Dataset:
    if value_size == 1024:
        return fair.GENERAL_DATASET
    if value_size == 8192:
        return fair.KVSEP_8KB_4GB_DATASET
    recordcount = max(32_768, BASE_DATA_BYTES // value_size)
    tag = f"source-fullspace-24B-{value_size}B-4GB"
    return fair.Dataset(
        name=f"4GB-{value_size}B",
        recordcount=int(recordcount),
        fieldlength=value_size,
        source_root=ROOT / "db" / f"ycsb-{tag}",
        source_tag=tag,
    )


BASE_DATASET = dataset_for_value_size(BASE_VALUE_SIZE)


def fmt_float(value: float) -> str:
    return f"{value:g}"


def workload_text(
    *,
    dataset: fair.Dataset,
    operationcount: int,
    warmup_ratio: float,
    warmup_operation: str,
    scan_length: int,
    zipfian_const: float,
    update_prop: float,
    scan_prop: float,
) -> str:
    return f"""# Generated by experiments/run_lorc_fullspace_ycsbe_matrix.py
recordcount={dataset.recordcount}
operationcount={operationcount}
warmup_ratio={warmup_ratio:.8f}
warmupoperation={warmup_operation}
warmupboundary=false
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

zeropadding=24
fieldcount=1
fieldlength={dataset.fieldlength}

readallfields=true
writeallfields=true

readproportion=0
updateproportion={update_prop:.8f}
scanproportion={scan_prop:.8f}
insertproportion=0

requestdistribution=orderedzipfian
zipfian_const={zipfian_const:.8f}

minscanlength={scan_length}
maxscanlength={scan_length}
scanlengthdistribution=uniform
"""


def validate_workload(path: Path) -> None:
    text = path.read_text()
    forbidden = ["hot_data_ratio=", "phased_ranges=", "requestdistribution=phased"]
    for token in forbidden:
        if token in text:
            raise RuntimeError(f"{path} contains forbidden manual-hotspot token: {token}")
    if "requestdistribution=orderedzipfian" not in text:
        raise RuntimeError(f"{path} is not an ordered scan-start zipfian workload")
    if "warmupoperation=same" not in text:
        raise RuntimeError(f"{path} does not warm up with the measured distribution")
    if "warmupboundary=false" not in text:
        raise RuntimeError(f"{path} can inject non-distribution boundary warmup scans")


def warmup_ops_for(
    dataset: fair.Dataset,
    scan_length: int,
    *,
    coverage: float,
    max_warmup_ops: int,
) -> int:
    coverage_ops = math.ceil(
        coverage * dataset.recordcount / max(scan_length, 1)
    )
    return max(20_000, min(max_warmup_ops, coverage_ops))


def write_workload(
    out_dir: Path,
    name: str,
    *,
    dataset: fair.Dataset,
    measured_ops: int,
    scan_length: int,
    zipfian_const: float,
    update_prop: float,
    warmup_coverage: float,
    max_warmup_ops: int,
) -> tuple[Path, int, int, float]:
    warmup_ops = warmup_ops_for(
        dataset,
        scan_length,
        coverage=warmup_coverage,
        max_warmup_ops=max_warmup_ops,
    )
    total_ops = measured_ops + warmup_ops
    warmup_ratio = warmup_ops / total_ops
    scan_prop = 1.0 - update_prop
    path = out_dir / f"{name}.properties"
    path.write_text(
        workload_text(
            dataset=dataset,
            operationcount=total_ops,
            warmup_ratio=warmup_ratio,
            warmup_operation="same",
            scan_length=scan_length,
            zipfian_const=zipfian_const,
            update_prop=update_prop,
            scan_prop=scan_prop,
        )
    )
    validate_workload(path)
    return path, total_ops, warmup_ops, warmup_ratio


def unique_datasets(items: list[RunItem]) -> list[fair.Dataset]:
    out: list[fair.Dataset] = []
    seen: set[tuple[str, int, int]] = set()
    for item in items:
        dataset = item.dataset
        key = (dataset.name, dataset.recordcount, dataset.fieldlength)
        if key in seen:
            continue
        seen.add(key)
        out.append(dataset)
    return out


def make_plan(
    out_dir: Path,
    *,
    suites: set[str] | None,
    measured_ops: int,
    warmup_coverage: float,
    max_warmup_ops: int,
) -> list[RunItem]:
    workload_dir = out_dir / "workloads"
    workload_dir.mkdir(parents=True, exist_ok=True)
    plan: list[RunItem] = []

    def enabled(suite: str) -> bool:
        return suites is None or suite in suites

    def add_suite(
        *,
        suite: str,
        x_value: str,
        x_label: str,
        dataset: fair.Dataset = BASE_DATASET,
        scan_length: int = BASE_SCAN_LENGTH,
        zipfian_const: float = BASE_ZIPFIAN,
        update_prop: float = 0.0,
        cache_budget_bytes: int = BASE_CACHE_BUDGET,
        threads: int = 1,
        single_thread_warmup: bool = False,
        lru_policy: str = "boundary_lru",
        variants: list[fair.Variant] | None = None,
        suite_measured_ops: int | None = None,
        timeout: int = 2400,
    ) -> None:
        if not enabled(suite):
            return
        run_measured_ops = suite_measured_ops or measured_ops
        workload_name = (
            f"{suite}_{x_value}_{dataset.name}_sl{scan_length}_"
            f"zipf{fmt_float(zipfian_const)}_upd{fmt_float(update_prop)}"
        ).replace(".", "p").replace("/", "_")
        workload, op_count, warmup_ops, warmup_ratio = write_workload(
            workload_dir,
            workload_name,
            dataset=dataset,
            measured_ops=run_measured_ops,
            scan_length=scan_length,
            zipfian_const=zipfian_const,
            update_prop=update_prop,
            warmup_coverage=warmup_coverage,
            max_warmup_ops=max_warmup_ops,
        )
        read_only = update_prop == 0.0
        for variant in variants or fair.VARIANTS:
            plan.append(
                RunItem(
                    suite=suite,
                    x_value=x_value,
                    x_label=x_label,
                    dataset=dataset,
                    workload=workload,
                    variant=variant,
                    read_only=read_only,
                    scan_length=scan_length,
                    zipfian_const=zipfian_const,
                    update_prop=update_prop,
                    scan_prop=1.0 - update_prop,
                    operationcount=op_count,
                    warmup_ops=warmup_ops,
                    warmup_ratio=warmup_ratio,
                    cache_budget_bytes=cache_budget_bytes,
                    threads=threads,
                    single_thread_warmup=single_thread_warmup,
                    lru_policy=lru_policy,
                    timeout=timeout,
                )
            )

    for scan_length in [5, 10, 20, 50, 100]:
        add_suite(
            suite="scan_length",
            x_value=str(scan_length),
            x_label=str(scan_length),
            scan_length=scan_length,
            timeout=3600 if scan_length <= 10 else 2400,
        )

    for value_size in [256, 512, 1024, 4096, 8192]:
        add_suite(
            suite="value_size",
            x_value=str(value_size),
            x_label=f"{value_size // 1024}KB" if value_size >= 1024 else f"{value_size}B",
            dataset=dataset_for_value_size(value_size),
            timeout=5400 if value_size <= 512 else 3600,
        )

    for zipfian_const in [0.0, 0.5, 0.8, 0.99, 1.2, 1.5]:
        add_suite(
            suite="zipfian",
            x_value=fmt_float(zipfian_const),
            x_label=fmt_float(zipfian_const),
            zipfian_const=zipfian_const,
            timeout=3000,
        )

    for update_pct in [0, 5, 10, 20, 50]:
        update_prop = update_pct / 100.0
        add_suite(
            suite="workload_mix",
            x_value=str(update_pct),
            x_label=f"{update_pct}%",
            update_prop=update_prop,
            suite_measured_ops=20_000 if update_pct >= 20 else measured_ops,
            timeout=5400 if update_pct >= 20 else 3600,
        )

    for budget_mb in [256, 512, 768, 1024, 1536, 2048]:
        add_suite(
            suite="cache_budget",
            x_value=str(budget_mb),
            x_label=f"{budget_mb}MB",
            cache_budget_bytes=budget_mb * MB,
            timeout=3000,
        )

    for threads in [1, 2, 4, 8, 16]:
        add_suite(
            suite="threads",
            x_value=str(threads),
            x_label=str(threads),
            threads=threads,
            single_thread_warmup=True,
            suite_measured_ops=80_000,
            timeout=3600,
        )

    policy_variants = [fair.VARIANTS[1], fair.VARIANTS[3]]
    for policy in ["boundary_lru", "physical_lru", "shortest_range"]:
        add_suite(
            suite="lru_policy",
            x_value=policy,
            x_label={
                "boundary_lru": "Boundary",
                "physical_lru": "Physical",
                "shortest_range": "Shortest",
            }[policy],
            scan_length=100,
            cache_budget_bytes=256 * MB,
            lru_policy=policy,
            variants=policy_variants,
            suite_measured_ops=20_000,
            timeout=3600,
        )

    return plan


