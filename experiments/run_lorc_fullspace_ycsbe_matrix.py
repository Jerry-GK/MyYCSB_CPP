def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=None)
    parser.add_argument("--summary", type=Path)
    parser.add_argument("--plot-only", action="store_true")
    parser.add_argument("--reload-sources", action="store_true")
    parser.add_argument("--suite", action="append", choices=SUITE_ORDER)
    parser.add_argument("--x-value", action="append")
    parser.add_argument("--max-runs", type=int)
    parser.add_argument("--measured-ops", type=int, default=BASE_MEASURED_OPS)
    parser.add_argument("--warmup-coverage", type=float, default=BASE_WARMUP_COVERAGE)
    parser.add_argument("--max-warmup-ops", type=int, default=MAX_WARMUP_OPS)
    parser.add_argument("--file-prewarm", action="store_true")
    args = parser.parse_args()

    out_dir = args.out or (
        ROOT
        / "result"
        / "log"
        / f"lorc_fullspace_ycsbe_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    )
    paper_summary = PAPER / "figures" / "experiments" / "lorc_fullspace_ycsbe_summary.csv"
    figure_dir = PAPER / "figures" / "experiments"

    if args.plot_only:
        if args.summary is None:
            raise SystemExit("--plot-only requires --summary")
        plot_all(args.summary, figure_dir)
        paper_summary.write_text(args.summary.read_text())
        print(f"summary={args.summary}")
        print(f"paper_summary={paper_summary}")
        return 0

    suites = set(args.suite) if args.suite else None
    plan = make_plan(
        out_dir,
        suites=suites,
        measured_ops=args.measured_ops,
        warmup_coverage=args.warmup_coverage,
        max_warmup_ops=args.max_warmup_ops,
    )
    if args.x_value:
        wanted = set(args.x_value)
        plan = [item for item in plan if item.x_value in wanted]
    prepare_sources(unique_datasets(plan), out_dir=out_dir, reload=args.reload_sources)
    rows = execute_plan(
        plan,
        out_dir=out_dir,
        max_runs=args.max_runs,
        file_prewarm=args.file_prewarm,
    )
    summary = out_dir / "lorc_fullspace_ycsbe_summary.csv"
    write_summary(rows, summary)
    if args.max_runs is None and suites is None:
        paper_summary.write_text(summary.read_text())
        plot_all(summary, figure_dir)
        print(f"paper_summary={paper_summary}")
    else:
        plot_all(summary, out_dir)
    print(f"summary={summary}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
