#!/usr/bin/env python3
"""Run a phased YCSB scan workload for hotspot stability/adaptation.

The workload has two cases:
  * stable: warmup and measured scans target the same hot interval.
  * shifted: warmup targets one hot interval, then the measured phase moves to
    a second interval. The measured phase is long enough for a cache layer to
    refill and amortize its materialization cost.

This is a robustness experiment, not the main upper-bound warmed-scan result.
"""

from __future__ import annotations

import argparse
import csv
from datetime import datetime
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

import run_lorc_fair_matrix as fair


ROOT = fair.ROOT
PAPER = fair.PAPER


def workload_text(
    *,
    dataset: fair.Dataset,
    scan_length: int,
    warmup_ops: int,
    measured_ops: int,
    stable: bool,
) -> str:
    hot_records = max(4096, dataset.recordcount // 20)
    old_start = dataset.recordcount // 4
    new_start = dataset.recordcount // 2
    old_end = old_start + hot_records - scan_length
    new_end = new_start + hot_records - scan_length
    measured_start = old_start if stable else new_start
    measured_end = old_end if stable else new_end
    phases = [
        f"{old_start}:{old_end}:{warmup_ops}",
        f"{measured_start}:{measured_end}:{measured_ops}",
    ]
    total_ops = warmup_ops + measured_ops
    return f"""# Generated by experiments/run_lorc_dynamic_hotspot.py
recordcount={dataset.recordcount}
operationcount={total_ops}
warmup_ratio={warmup_ops / total_ops:.8f}
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

zeropadding=24
fieldcount=1
fieldlength={dataset.fieldlength}

readallfields=true
writeallfields=true

readproportion=0
updateproportion=0
scanproportion=1
insertproportion=0

requestdistribution=phased
phased_ranges={";".join(phases)}

minscanlength={scan_length}
maxscanlength={scan_length}
scanlengthdistribution=uniform
"""


def run_experiment(*, out_dir: Path, reload_source: bool) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    dataset = fair.value_dataset(1024)
    fair.prepare_sources(
        [dataset],
        budget=fair.DEFAULT_CACHE_BUDGET,
        out_dir=out_dir,
        reload=reload_source,
    )
    workload_dir = out_dir / "workloads"
    workload_dir.mkdir(parents=True, exist_ok=True)

    scan_length = 20
    warmup_ops = 40_000
    measured_ops = 80_000
    rows: list[dict[str, str | int | float]] = []

    for case, stable in [("stable", True), ("shifted", False)]:
        workload = workload_dir / f"dynamic_{case}.properties"
        workload.write_text(
            workload_text(
                dataset=dataset,
                scan_length=scan_length,
                warmup_ops=warmup_ops,
                measured_ops=measured_ops,
                stable=stable,
            )
        )
        for variant in fair.VARIANTS:
            source = dataset.source_path(variant.engine)
            if not source.exists():
                raise FileNotFoundError(source)
            props = fair.system_props(
                variant, fair.DEFAULT_CACHE_BUDGET, direct_reads="false"
            )
            props.update(fair.read_only_props(variant))
            log_name = f"dynamic_hotspot__{case}__{variant.key}"
            rc, text, time_info = fair.run_ycsb(
                mode="run",
                variant=variant,
                workload=workload,
                db_path=source,
                run_dir=out_dir,
                log_name=log_name,
                props=props,
                threads=1,
                timeout=1800,
                random_seed=700 + (0 if stable else 100) + len(variant.label),
            )
            parsed = fair.parse_log(text)
            if rc != 0:
                raise RuntimeError(f"Run failed for {case}/{variant.label}\n{text[-2500:]}")
            full_hit = float(parsed.get("lorc_full_hit_rate", 0.0))
            rows.append(
                {
                    "case": case,
                    "variant": variant.label,
                    "variant_key": variant.key,
                    "engine": variant.engine,
                    "dataset": dataset.name,
                    "recordcount": dataset.recordcount,
                    "fieldlength": dataset.fieldlength,
                    "scan_length": scan_length,
                    "warmup_ops": warmup_ops,
                    "measured_ops": measured_ops,
                    "cache_budget_bytes": fair.DEFAULT_CACHE_BUDGET,
                    "throughput_ops_sec": float(parsed.get("throughputops/sec", 0.0)),
                    "scan_avg_us": float(parsed.get("scan_avg_us", 0.0)),
                    "scan_p99_us": float(parsed.get("scan_p99_us", 0.0)),
                    "lorc_full_hit_rate": full_hit,
                    "storage_touch_scan_ratio": max(0.0, 1.0 - full_hit),
                    "lorc_hit_size_rate": float(parsed.get("lorc_hit_size_rate", 0.0)),
                    "max_rss_kb": int(time_info.get("max_rss_kb", 0)),
                    "fs_inputs": int(time_info.get("fs_inputs", 0)),
                    "fs_outputs": int(time_info.get("fs_outputs", 0)),
                    "log": str(out_dir / f"{log_name}.log"),
                }
            )

    summary = out_dir / "lorc_dynamic_hotspot_summary.csv"
    with summary.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    return summary


def plot(summary: Path, figure: Path) -> None:
    with summary.open() as f:
        rows = list(csv.DictReader(f))
    cases = ["stable", "shifted"]
    variants = [v.label for v in fair.VARIANTS]
    index = {(r["case"], r["variant"]): r for r in rows}
    colors = {
        "RocksDB": "#6D6D6D",
        "RocksDB+LORC": "#3B6EA8",
        "BlobDB": "#A66A2C",
        "BlobDB+LORC": "#3D8B5B",
        "LSbM": "#8A5EA8",
    }
    hatches = {
        "RocksDB": "",
        "RocksDB+LORC": "///",
        "BlobDB": "",
        "BlobDB+LORC": "///",
        "LSbM": "...",
    }
    plt.rcParams.update(
        {
            "font.size": 8.4,
            "axes.labelsize": 8.4,
            "legend.fontsize": 7.8,
            "xtick.labelsize": 8,
            "ytick.labelsize": 8,
            "figure.dpi": 180,
            "pdf.fonttype": 42,
            "ps.fonttype": 42,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )
    fig, axes = plt.subplots(1, 2, figsize=(7.35, 2.45), constrained_layout=True)
    metrics = [
        ("Throughput", "throughput_ops_sec", "K scans/s", lambda v: v / 1000.0),
        ("p99 scan latency", "scan_p99_us", "us", lambda v: v),
    ]
    width = 0.15
    xs = list(range(len(cases)))
    for ax, (title, key, ylabel, transform) in zip(axes, metrics):
        for i, variant in enumerate(variants):
            values = [
                transform(float(index[(case, variant)][key]))
                for case in cases
            ]
            bars = ax.bar(
                [x + (i - 2) * width for x in xs],
                values,
                width,
                color=colors[variant],
                edgecolor="#222222",
                linewidth=0.45,
                label=variant,
            )
            for bar in bars:
                bar.set_hatch(hatches[variant])
        ax.set_title(title)
        ax.set_ylabel(ylabel)
        ax.set_xticks(xs)
        ax.set_xticklabels(["Stable", "Shifted"])
        if key == "scan_p99_us":
            ax.set_yscale("log")
            ax.set_ylabel("us (log scale)")
        ax.grid(axis="y", color="#E7E7E7", linewidth=0.65)
        ax.set_axisbelow(True)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles,
        labels,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.08),
        ncol=5,
        frameon=False,
        columnspacing=0.8,
        handlelength=1.1,
    )
    figure.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(figure, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path)
    parser.add_argument("--summary", type=Path)
    parser.add_argument("--plot-only", action="store_true")
    parser.add_argument("--reload-source", action="store_true")
    args = parser.parse_args()

    figure = PAPER / "figures" / "experiments" / "eval_dynamic_hotspot.pdf"
    paper_summary = PAPER / "figures" / "experiments" / "lorc_dynamic_hotspot_summary.csv"

    if args.plot_only:
        if not args.summary:
            raise SystemExit("--plot-only requires --summary")
        plot(args.summary, figure)
        paper_summary.write_text(args.summary.read_text())
        print(f"summary={args.summary}")
        print(f"figure={figure}")
        return 0

    out_dir = args.out or (
        ROOT / "result" / "log" / f"lorc_dynamic_hotspot_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    )
    summary = run_experiment(out_dir=out_dir, reload_source=args.reload_source)
    plot(summary, figure)
    paper_summary.write_text(summary.read_text())
    print(f"summary={summary}")
    print(f"paper_summary={paper_summary}")
    print(f"figure={figure}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
