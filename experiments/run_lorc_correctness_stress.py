#!/usr/bin/env python3
"""Run LORC scan-validation stress tests with foreground updates.

The RocksDB wrapper validates each LORC scan against a normal RocksDB iterator
for the first N scans. This script keeps the run small enough for regression
use but includes copied writable databases and automatic compaction.
"""

from __future__ import annotations

import csv
import shutil
from datetime import datetime
from pathlib import Path

import run_lorc_fair_matrix as fair
import run_lorc_standard_ycsb as standard


ROOT = fair.ROOT
PAPER = fair.PAPER


def workload_text() -> str:
    return """# Generated by experiments/run_lorc_correctness_stress.py
recordcount=100000
operationcount=30000
warmup_ratio=0.16666667
warmupoperation=scan
insertorder=random

workload=com.yahoo.ycsb.workloads.CoreWorkload

fieldcount=10
fieldlength=100
readallfields=true
writeallfields=true

readproportion=0.20
updateproportion=0.20
scanproportion=0.60
insertproportion=0

requestdistribution=zipfian

minscanlength=20
maxscanlength=20
scanlengthdistribution=uniform
"""


def run() -> Path:
    out_dir = ROOT / "result" / "log" / f"lorc_correctness_stress_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
    out_dir.mkdir(parents=True, exist_ok=True)
    standard.load_sources(out_dir, budget=fair.DEFAULT_CACHE_BUDGET, reload=False)
    workload = out_dir / "correctness_stress.properties"
    workload.write_text(workload_text())
    variants = [fair.VARIANTS[1], fair.VARIANTS[3]]
    rows: list[dict[str, str | int | float]] = []
    for variant in variants:
        source = standard.standard_source_path(variant.engine)
        work_db = out_dir / "workdb" / variant.key
        if work_db.exists():
            shutil.rmtree(work_db)
        work_db.parent.mkdir(parents=True, exist_ok=True)
        shutil.copytree(source, work_db)
        props = fair.system_props(variant, fair.DEFAULT_CACHE_BUDGET, direct_reads="false")
        props.update(
            {
                "rocksdb.disable_auto_compactions": "false",
                "rocksdb.create_if_missing": "false",
                "rocksdb.destroy": "false",
                "rocksdb.read_only": "false",
                "rocksdb.deserialize_on_read": "true",
                "rocksdb.validate_scan_with_iterator": "true",
                "rocksdb.validate_scan_limit": "5000",
            }
        )
        rc, text, time_info = fair.run_ycsb(
            mode="run",
            variant=variant,
            workload=workload,
            db_path=work_db,
            run_dir=out_dir,
            log_name=f"correctness_stress__{variant.key}",
            props=props,
            threads=1,
            timeout=1800,
            random_seed=909,
        )
        shutil.rmtree(work_db)
        parsed = fair.parse_log(text)
        if rc != 0:
            raise RuntimeError(f"Correctness stress failed for {variant.label}\n{text[-2500:]}")
        rows.append(
            {
                "variant": variant.label,
                "variant_key": variant.key,
                "returncode": rc,
                "validated_scan_limit": 5000,
                "throughput_ops_sec": float(parsed.get("throughputops/sec", 0.0)),
                "scan_count": int(parsed.get("scan_count", 0)),
                "scan_avg_us": float(parsed.get("scan_avg_us", 0.0)),
                "scan_p99_us": float(parsed.get("scan_p99_us", 0.0)),
                "read_count": int(parsed.get("read_count", 0)),
                "update_count": int(parsed.get("update_count", 0)),
                "lorc_full_hit_rate": float(parsed.get("lorc_full_hit_rate", 0.0)),
                "lorc_hit_size_rate": float(parsed.get("lorc_hit_size_rate", 0.0)),
                "max_rss_kb": int(time_info.get("max_rss_kb", 0)),
                "log": str(out_dir / f"correctness_stress__{variant.key}.log"),
            }
        )
    summary = out_dir / "lorc_correctness_stress_summary.csv"
    with summary.open("w", newline="") as f:
        writer = csv.DictWriter(
            f, fieldnames=list(rows[0].keys()), lineterminator="\n"
        )
        writer.writeheader()
        writer.writerows(rows)
    paper_summary = PAPER / "figures" / "experiments" / "lorc_correctness_stress_summary.csv"
    paper_summary.write_text(summary.read_text())
    print(f"summary={summary}")
    print(f"paper_summary={paper_summary}")
    return summary


if __name__ == "__main__":
    run()
