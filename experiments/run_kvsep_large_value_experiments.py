@dataclass(frozen=True)
class Experiment:
    name: str
    variants: tuple[str, ...]
    scan_length: int = 50
    hot_ratio: float = 0.20
    measured_ops: int = 6000
    min_warmup_ops: int = 15000
    coverage_factor: float = 6.0
    distribution: str = "zipfian"


