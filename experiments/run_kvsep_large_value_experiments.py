@dataclass(frozen=True)
class Variant:
    label: str
    db: str
    prop_file: str
    lorc: bool
    group: str
    props: dict[str, str] = field(default_factory=dict)

    @property
    def key(self) -> str:
        return (
            self.label.lower()
            .replace("+", "_")
            .replace(" ", "_")
            .replace("(", "")
            .replace(")", "")
            .replace("/", "_")
        )

    @property
    def source_path(self) -> Path:
        return (
            ROOT
            / "db"
            / f"ycsb-{SOURCE_POSTFIX}"
            / f"ycsb-{self.db}-{SOURCE_POSTFIX}-random"
        )


